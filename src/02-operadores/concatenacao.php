<?php

/**
 * O operadore de contacenação é utilizado para unir duas ou mais strings em uma única string.
 * O operador de concatenação em PHP é o ponto (.) e é usado para concatenar strings.
 * Exemplo:
 * $string1 = "Olá, ";
 * $string2 = "mundo!";
 * $resultado = $string1 . $string2; // O resultado será "Olá, mundo!"
 * O operador de concatenação pode ser usado para criar mensagens dinâmicas,
 * combinar variáveis e strings literais, ou construir strings complexas a partir 
 * de partes menores.  
 */
$string1 = "Olá, ";
$string2 = "mundo!";
$resultado = $string1 . $string2;
echo $resultado . "<br>" . "\n"; // Saída: "Olá, mundo!"    